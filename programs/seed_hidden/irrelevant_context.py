FAMILY = "irrelevant_context"
MECHANISM = "prepend 1-2 topically related but irrelevant sentences generated by the LLM"

PROMPT = """Write one or two sentences of background text on the same general topic as the question below,
but which give NO information about its answer and do not mention any of the answer options.
Output only the sentences.

Question: {q}"""


def mutate(seed, llm, rng):
    ctx = llm(PROMPT.format(q=seed["question"]), temperature=0.9).strip()
    return {"question": ctx + "\n\n" + seed["question"], "choices": list(seed["choices"])}


def check(seed, mutated):
    q0, q1 = seed["question"], mutated["question"]
    if not q1.endswith(q0):
        return "original question not preserved verbatim"
    ctx = q1[: -len(q0)].strip()
    if not ctx or len(ctx) > 500:
        return "context empty or too long"
    for c in seed["choices"]:
        if len(c) > 3 and c.lower() in ctx.lower():
            return f"context mentions option '{c}'"
    return True
